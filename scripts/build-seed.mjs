// Generates supabase/seed.sql from content/lessons.json.
// Usage: npm run seed:build   (then `npm run db:reset` to load it locally)
import { readFileSync, writeFileSync } from 'node:fs';

const TOPICS = [
  ['daily-conversation', 'Daily Conversation'],
  ['movies-tv', 'Movies & TV Shows'],
  ['podcast-interviews', 'Podcast & Interviews'],
  ['education', 'Education'],
  ['travel', 'Travel'],
  ['business-career', 'Business & Career'],
  ['entertainment', 'Entertainment'],
];
const LEVELS = ['beginner', 'elementary', 'intermediate', 'upper_intermediate', 'advanced'];
const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/;

const { lessons } = JSON.parse(readFileSync(new URL('../content/lessons.json', import.meta.url), 'utf8'));
const q = (s) => (s == null ? 'null' : `'${String(s).replaceAll("'", "''")}'`);

// Validate before writing, so a typo fails here rather than inside Postgres.
const errors = [];
const ids = new Set();
for (const l of lessons) {
  const where = `lesson ${l.id ?? '?'} (${l.title ?? 'untitled'})`;
  if (!UUID.test(l.id ?? '')) errors.push(`${where}: invalid id`);
  if (ids.has(l.id)) errors.push(`${where}: duplicate id`);
  ids.add(l.id);
  if (!['en', 'zh'].includes(l.language)) errors.push(`${where}: language must be en or zh`);
  if (l.language === 'zh' && !(l.hsk >= 1 && l.hsk <= 6)) errors.push(`${where}: Chinese lessons need hsk 1-6`);
  if (l.language === 'en' && l.hsk != null) errors.push(`${where}: hsk only applies to Chinese`);
  if (!LEVELS.includes(l.level)) errors.push(`${where}: unknown level ${l.level}`);
  if (!TOPICS.some(([slug]) => slug === l.topic)) errors.push(`${where}: unknown topic ${l.topic}`);
  if (!(l.difficulty >= 1 && l.difficulty <= 5)) errors.push(`${where}: difficulty 1-5`);
  if (!Array.isArray(l.sentences) || l.sentences.length === 0) errors.push(`${where}: no sentences`);
  for (const [i, s] of (l.sentences ?? []).entries()) {
    if (!Array.isArray(s) || !s[0]?.trim()) errors.push(`${where}: sentence ${i + 1} is empty`);
    if (s[0]?.length > 1000) errors.push(`${where}: sentence ${i + 1} too long`);
    if (l.language === 'zh' && /[A-Za-z]/.test(s[0] ?? '')) errors.push(`${where}: sentence ${i + 1} has Latin letters`);
  }
}
if (errors.length) {
  console.error(errors.join('\n'));
  process.exit(1);
}

const out = [];
out.push('-- GENERATED by scripts/build-seed.mjs from content/lessons.json. Do not edit by hand.');
out.push('-- Only shared reference data lives here. User data is never seeded.', '');
out.push('insert into public.topics (slug, name) values');
out.push(TOPICS.map(([s, n]) => `  (${q(s)}, ${q(n)})`).join(',\n') + '\non conflict (slug) do nothing;', '');
out.push('-- Demo lessons (is_sample = true): audio is produced by text-to-speech in the browser.');
for (const l of lessons) {
  out.push(
    `insert into public.lessons (id, title, description, language, level, hsk_level, topic_id, source, difficulty, is_published, is_sample)`,
    `select ${q(l.id)}, ${q(l.title)}, ${q(l.description)}, ${q(l.language)}, ${q(l.level)}, ${l.hsk ?? 'null'}, id, 'LinguaFlow', ${l.difficulty}, true, true`,
    `from public.topics where slug = ${q(l.topic)}`,
    `on conflict (id) do nothing;`,
    // Safe to re-run: only fills a lesson that has no sentences yet.
    `insert into public.lesson_sentences (lesson_id, position, text, translation_vi)`,
    `select ${q(l.id)}::uuid, v.position, v.text, v.translation_vi from (values`,
    l.sentences.map(([text, vi], i) => `  (${i + 1}, ${q(text.trim())}, ${q(vi)})`).join(',\n'),
    `) as v(position, text, translation_vi)`,
    `where not exists (select 1 from public.lesson_sentences where lesson_id = ${q(l.id)});`,
    '',
  );
}
// ───────────── Word families (IELTS word forms) ─────────────
const POS_CODE = { n: 'noun', v: 'verb', adj: 'adj', adv: 'adv' };
const { families } = JSON.parse(readFileSync(new URL('../content/word-families.json', import.meta.url), 'utf8'));

/** Candidate dictionary forms of an inflected word: groups → group, studies → study, stopped → stop… */
function lemmas(word) {
  const w = word.toLowerCase();
  const out = [w];
  if (w.endsWith('ies')) out.push(w.slice(0, -3) + 'y');
  if (w.endsWith('es')) out.push(w.slice(0, -2));
  if (w.endsWith('s')) out.push(w.slice(0, -1));
  if (w.endsWith('ied')) out.push(w.slice(0, -3) + 'y');
  if (w.endsWith('ed')) out.push(w.slice(0, -2), w.slice(0, -1), w.slice(0, -3));
  if (w.endsWith('ing')) out.push(w.slice(0, -3), w.slice(0, -3) + 'e', w.slice(0, -4));
  return out;
}

const famErrors = [];
const famIds = new Set();
const famOut = ['', '-- Word families (IELTS word forms), from content/word-families.json.'];
for (const f of families) {
  const id = f.h;
  const where = `family "${id}"`;
  if (!/^[a-z-]{2,40}$/.test(id)) famErrors.push(`${where}: invalid headword`);
  if (famIds.has(id)) famErrors.push(`${where}: duplicate`);
  famIds.add(id);
  const members = (f.m ?? []).map(([word, pos, vi]) => {
    if (!POS_CODE[pos]) famErrors.push(`${where}: "${word}" has unknown pos ${pos}`);
    return { word, pos: POS_CODE[pos], vi };
  });
  if (members.length < 2) famErrors.push(`${where}: needs at least 2 members`);
  const examples = (f.x ?? []).map(([sentence, why, override]) => {
    const m = /\[([^\]]+)\]/.exec(sentence);
    if (!m) { famErrors.push(`${where}: example without [answer]: ${sentence}`); return null; }
    const answer = m[1];
    const candidates = lemmas(answer);
    const matches = members.filter((mb) => candidates.includes(mb.word.toLowerCase()));
    const exact = matches.filter((mb) => mb.word.toLowerCase() === answer.toLowerCase());
    const pool = exact.length ? exact : matches;
    let pos = override ? POS_CODE[override] : [...new Set(pool.map((p) => p.pos))].length === 1 ? pool[0].pos : null;
    if (!pool.length) famErrors.push(`${where}: answer "${answer}" is not a member (or inflection) of the family`);
    else if (!pos) famErrors.push(`${where}: answer "${answer}" is ambiguous (${pool.map((p) => p.pos).join('/')}); add a pos override`);
    // Show a base word that differs from the answer, so the learner has to change the form.
    const lemma = (pool[0] ?? {}).word ?? answer;
    const base = id !== lemma.toLowerCase() ? id : (members.find((mb) => mb.word.toLowerCase() !== lemma.toLowerCase() && mb.pos !== pos) ?? members.find((mb) => mb.word.toLowerCase() !== lemma.toLowerCase()))?.word ?? id;
    return { sentence, answer, pos, base, why };
  });
  famOut.push(
    `insert into public.word_families (id, note, traps) values (${q(id)}, ${q(f.note ?? null)}, ${f.t?.length ? `array[${f.t.map(q).join(', ')}]` : `'{}'`}) on conflict (id) do nothing;`,
    `insert into public.word_family_members (family_id, word, pos, meaning_vi) values`,
    members.map((mb) => `  (${q(id)}, ${q(mb.word)}, ${q(mb.pos)}, ${q(mb.vi)})`).join(',\n'),
    `on conflict (family_id, word, pos) do nothing;`,
  );
  const ex = examples.filter(Boolean);
  if (ex.length) {
    famOut.push(
      `insert into public.word_family_examples (family_id, sentence, answer, answer_pos, base_word, why)`,
      `select v.* from (values`,
      ex.map((e) => `  (${q(id)}, ${q(e.sentence)}, ${q(e.answer)}, ${q(e.pos)}, ${q(e.base)}, ${q(e.why)})`).join(',\n'),
      `) as v(family_id, sentence, answer, answer_pos, base_word, why)`,
      `where not exists (select 1 from public.word_family_examples where family_id = ${q(id)});`,
    );
  }
}
if (famErrors.length) {
  console.error(famErrors.join('\n'));
  process.exit(1);
}
out.push(...famOut, '');

writeFileSync(new URL('../supabase/seed.sql', import.meta.url), out.join('\n'));
const total = lessons.reduce((n, l) => n + l.sentences.length, 0);
console.log(`seed.sql: ${lessons.length} lessons, ${total} sentences, ${families.length} word families`);
